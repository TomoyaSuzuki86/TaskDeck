import { describe, test } from 'vitest';

describe('Task Deck task ordering', () => {
  test.todo('期限切れタスクが他のすべてのタスクより先に表示される');
  test.todo('今日中のタスクが期限切れタスクの次に表示される');
  test.todo('明日のタスクが今日中のタスクの次に表示される');
  test.todo('2日後以降のタスクは期日が近い順に表示される');
  test.todo('期日なしタスクは今日中のタスクとして扱われる');
  test.todo('完了済みタスクはメインデッキに表示されない');
  test.todo('保管済みタスクはメインデッキに表示されない');
  test.todo('通常の今日中タスクは最大3件まで表示される');
  test.todo('今日中タスクがない場合は明日以降の近いタスクでデッキを補う');
  test.todo('同じ期日のタスクはorder順に表示される');
  test.todo('今日中タスクが3件あっても期限切れタスクは専用の最上部エリアに表示される');
  test.todo('明日以降エリアには最も近い未来のタスクが補助的に表示される');
  test.todo('同じ表示セッション中にスヌーズされたタスクは表示されない');
  test.todo('保管リスト画面では保管済みタスクを表示できる');
});
